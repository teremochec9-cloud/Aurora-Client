package dev.aurora.client.util;

/**
 * Единое время кадра Aurora.
 *
 * <p>Системное время читается ОДИН раз за кадр — в начале отрисовки GUI
 * (миксин {@code GuiRendererMixin}). Все анимации, дым и эффекты клиента
 * берут время отсюда: это убирает десятки вызовов
 * {@code System.currentTimeMillis()} на кадр и гарантирует, что элементы,
 * анимируемые в одном кадре, движутся синхронно, без «рваных» фаз.</p>
 *
 * <p>ФИКС 1.0.7 (главная причина «мерцания» и дёрганости): раньше
 * {@link #seconds()} возвращал абсолютные эпоха-миллисекунды (≈1.8·10¹²)
 * в float. У float рядом с таким числом шаг сетки ≈131 секунда — время
 * анимаций «замерзало», а затем скачком прыгало: звёзды, сияние, иконка,
 * дуги ESP телепортировались (то самое «мелькает противно»). Теперь
 * время отсчитывается от якоря запуска клиента — значения маленькие,
 * точность float абсолютная, движение идеально плавное.</p>
 *
 * <p>Побочный бонус: время кадра можно подменить (например, в тестах или
 * при паузе отладчика) — и весь интерфейс замрёт согласованно.</p>
 */
public final class FrameClock {
    /** Якорь: все значения — миллисекунды от момента запуска клиента. */
    private static final long ZERO = System.currentTimeMillis();

    private static volatile long frame = System.currentTimeMillis() - ZERO;

    private FrameClock() {
    }

    /** Начало нового кадра. Вызывается один раз за кадр из миксина GUI-рендера. */
    public static void refresh() {
        frame = System.currentTimeMillis() - ZERO;
    }

    /** Время текущего кадра в миллисекундах от запуска клиента. */
    public static long now() {
        return frame;
    }

    /** Время текущего кадра в секундах от запуска (для синусоид и дрейфа частиц). */
    public static float seconds() {
        return frame / 1000.0f;
    }
}
